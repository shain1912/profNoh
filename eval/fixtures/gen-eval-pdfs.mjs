const html = (s) => `<!doctype html><html><head><meta charset="utf-8"><style>
  body { font-family: "Malgun Gothic", sans-serif; }
  section { page-break-after: always; padding: 60px; }
  h1 { font-size: 26px; color: #1a1a2e; } p { font-size: 15px; line-height: 1.9; }
</style></head><body>
${s.pages.map((p) => `<section><h1>${p.h}</h1><p>${p.b}</p></section>`).join('\n')}
</body></html>`;

const browser = await chromium.launch();
const page = await browser.newPage();
for (const [key, s] of Object.entries(SUBJECTS)) {
  await page.setContent(html(s));
  await page.pdf({ path: resolve(here, key + '.pdf'), printBackground: true, format: 'A4' });
  console.log('generated', key + '.pdf');
}
await browser.close();


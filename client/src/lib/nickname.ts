// 닉네임 자동 생성 — "차분한 수달 42" (한국어 형용사 + 동물 + 숫자)
// 강당 모드 1탭 입장용 (R2 A1-3). /join 의 닉네임 입력 maxLength=12 이내가 되도록
// 형용사 ≤4자, 동물 ≤3자, 숫자 2자리로 제한한다 (최대 4+1+3+1+2 = 11자).

const ADJECTIVES = [
  '차분한', '용감한', '느긋한', '재빠른', '다정한', '엉뚱한', '씩씩한', '조용한',
  '명랑한', '수줍은', '든든한', '상냥한', '똑똑한', '부지런한', '유쾌한', '성실한',
  '활발한', '침착한', '너그러운', '당당한', '깔끔한', '포근한', '반짝이는', '호기심',
  '느린', '빠른', '작은', '커다란', '푸른', '붉은', '노란', '하얀',
];

const ANIMALS = [
  '수달', '고래', '펭귄', '여우', '판다', '토끼', '거북', '부엉이',
  '다람쥐', '고슴도치', '알파카', '너구리', '해달', '돌고래', '코알라', '늑대',
  '사슴', '기린', '하마', '두더지', '참새', '까치', '오리', '문어',
  '해마', '상어', '치타', '표범', '곰', '양', '말', '소',
];

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 예: "차분한 수달 42" */
export function generateNickname(): string {
  const n = Math.floor(Math.random() * 99) + 1; // 1~99
  return `${pick(ADJECTIVES)} ${pick(ANIMALS)} ${n}`;
}

/** 자동 생성 닉네임 형태인지 (형용사 동물 숫자) — 검증 스크립트·UI 힌트용 */
export const AUTO_NICKNAME_RE = /^\S{1,5} \S{1,4} \d{1,2}$/;
